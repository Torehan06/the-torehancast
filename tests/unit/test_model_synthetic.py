"""Known-truth elections built entirely in memory, without archives or feeds.

Six counties start at a tied statewide baseline of 21,000 votes. Tonight every
county swings D+10 points and turnout rises 20%: D 13,860, R 11,340, D+10.0.
Early votes lean 30 points more D than each county overall; Election Day leans
20 points more R. Their 40/60 split preserves the independently specified totals.
"""

from dataclasses import replace
import math

import pandas as pd
import pytest

from torehancast.model.composition import CompositionPrior
from torehancast.model.simulate import RaceModel, RacePrior
from torehancast.model.tau import HistoricalParams
from torehancast.schema import ALL, EARLY, ELECTION_DAY, Cell, Snapshot

# Literal counts, not generated by the model or its projection helpers.
BASELINE = [
    ("A", 600, 400), ("B", 800, 1200), ("C", 2100, 900),
    ("D", 1200, 2800), ("E", 2500, 2500), ("F", 3300, 2700),
]
TRUTH = [
    ("A", 780, 420), ("B", 1080, 1320), ("C", 2700, 900),
    ("D", 1680, 3120), ("E", 3300, 2700), ("F", 4320, 2880),
]
PARAMS = HistoricalParams(
    tau_swing=0.04, tau_turnout=0.08,
    systematic_swing=0.03, systematic_turnout=0.05,
    composition=CompositionPrior(0.2, 0.1, 0.1, 0.05),
    reference_votes=3500,
)
PRIOR = RacePrior(margin=-0.10, margin_sd=0.15, turnout_ratio=1.0, turnout_sd=0.2)


def _cells(rows, mode):
    cells = []
    for unit, d, r in rows:
        if mode == "all":
            cells.append(Cell(unit, ALL, {"D": d, "R": r}))
        else:
            # 40% of votes, margin 30 points more D than the county overall.
            early_d = (20 * d + 3 * (d + r)) // 50
            early_r = (20 * r - 3 * (d + r)) // 50
            cells.extend([
                Cell(unit, EARLY, {"D": early_d, "R": early_r}),
                Cell(unit, ELECTION_DAY, {"D": d - early_d, "R": r - early_r}),
            ])
    return cells


def _model(mode):
    baseline = pd.DataFrame([
        {"unit_id": c.unit_id, "vote_type": c.vote_type, **c.votes}
        for c in _cells(BASELINE, mode)
    ])
    return RaceModel(baseline, PRIOR, PARAMS)


def _snapshot(cells, *, complete=False, reporting=None):
    return Snapshot(
        "XX", "Synthetic Senate", None, cells,
        unit_reporting=reporting or {},
        cell_complete={(c.unit_id, c.vote_type): 1.0 for c in cells} if complete else {},
    )


def _assert_valid(result):
    assert all(math.isfinite(x) for x in [
        *result.p_win.values(), result.margin_median, *result.margin_80,
        *result.margin_95, result.expected_votes, result.share_counted,
    ])
    assert all(0 <= x <= 1 for x in result.p_win.values())
    assert sum(result.p_win.values()) == pytest.approx(1)
    assert -1 <= result.margin_95[0] <= result.margin_80[0] <= result.margin_median
    assert result.margin_median <= result.margin_80[1] <= result.margin_95[1] <= 1
    assert result.expected_votes >= result.reported_votes
    assert 0 <= result.share_counted <= 1


@pytest.mark.parametrize("mode", ["split", "all"])
def test_unreported_state_retains_uncertainty(mode):
    result = _model(mode).run(_snapshot([]), n_draws=4000, seed=7)
    _assert_valid(result)
    assert result.reported_votes == 0
    assert result.share_counted == 0
    assert result.margin_95[0] < -0.10 < 0.10 < result.margin_95[1]
    assert 0 < result.p_win["D"] < 0.5  # the deliberately wrong prior favours R


@pytest.mark.parametrize("mode", ["split", "all"])
def test_reported_counties_teach_swing_and_turnout(mode):
    model = _model(mode)
    before = model.run(_snapshot([]), n_draws=4000, seed=7)
    # A-C are not the largest counties, so most votes still need extrapolation.
    after = model.run(_snapshot(_cells(TRUTH[:3], mode), complete=True), n_draws=4000, seed=7)
    _assert_valid(after)
    assert after.reported_votes == 7200
    assert after.p_win["D"] > 0.5 > before.p_win["D"]
    assert after.margin_median == pytest.approx(0.10, abs=0.03)
    assert after.margin_95[0] <= 0.10 <= after.margin_95[1]
    assert after.margin_95[1] - after.margin_95[0] < before.margin_95[1] - before.margin_95[0]
    assert after.expected_votes == pytest.approx(25_200, rel=0.1)


@pytest.mark.parametrize("mode", ["split", "all"])
@pytest.mark.parametrize("winner", ["D", "R"])
def test_complete_state_equals_known_tally_despite_wrong_prior(mode, winner):
    truth = TRUTH if winner == "D" else [(u, r, d) for u, d, r in TRUTH]
    model = _model(mode)
    # The final tally must override even a strong prior for the wrong candidate.
    model.prior = replace(PRIOR, margin=-0.3 if winner == "D" else 0.3, margin_sd=0.02)
    result = model.run(_snapshot(_cells(truth, mode), complete=True), n_draws=2000, seed=7)
    _assert_valid(result)
    margin = 0.10 if winner == "D" else -0.10
    assert result.reported_votes == 25_200
    assert result.expected_votes == 25_200
    assert result.share_counted == 1
    assert result.margin_median == pytest.approx(margin)
    assert result.margin_80 == pytest.approx((margin, margin))
    assert result.margin_95 == pytest.approx((margin, margin))
    assert result.p_win[winner] == 1


@pytest.mark.parametrize("mode", ["split", "all"])
def test_partial_count_preserves_votes_and_contains_truth(mode):
    cells = [Cell(c.unit_id, c.vote_type, {k: v // 2 for k, v in c.votes.items()})
             for c in _cells(TRUTH, mode)]
    result = _model(mode).run(
        _snapshot(cells, reporting={u: 0.5 for u, _, _ in TRUTH}), n_draws=4000, seed=7,
    )
    _assert_valid(result)
    assert result.reported_votes == 12_600
    assert 0 < result.share_counted < 1
    assert result.margin_95[0] <= 0.10 <= result.margin_95[1]
    assert result.margin_95[1] > result.margin_95[0]


@pytest.mark.parametrize("mode", ["split", "all"])
def test_complete_zero_vote_county_adds_no_projected_votes(mode):
    # F has a nonzero baseline but explicitly reports a completed zero tally.
    # The remaining counties total D 9,540, R 8,460: 18,000 votes, D+6.0.
    truth = [*TRUTH[:5], ("F", 0, 0)]
    model = _model(mode)
    result = model.run(_snapshot(_cells(truth, mode), complete=True), n_draws=2000, seed=7)
    _assert_valid(result)
    assert result.reported_votes == 18_000
    assert result.expected_votes == 18_000
    assert result.share_counted == 1
    assert result.margin_median == pytest.approx(0.06)
    assert result.margin_95 == pytest.approx((0.06, 0.06))
    county = model.last_counties.set_index("unit_id").loc["F"]
    assert county.status == "complete"
    assert county.expected_votes == 0


@pytest.mark.parametrize("mode", ["split", "all"])
def test_unknown_county_votes_are_kept_and_flagged(mode):
    cells = [*_cells(TRUTH, mode), Cell("NEW", ALL, {"D": 100, "R": 300})]
    result = _model(mode).run(_snapshot(cells, complete=True), n_draws=2000, seed=7)
    _assert_valid(result)
    assert result.reported_votes == 25_600
    assert result.expected_votes == 25_600
    assert result.margin_median == pytest.approx(2320 / 25_600)
    assert any("NEW/all" in warning for warning in result.warnings)
